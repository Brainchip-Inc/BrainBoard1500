#!/usr/bin/env python
"""Generate the sample inputs that the BrainBoard1500 examples use for self tests.

  samples_vww       two 96x96x3 tiles of the Dev Hub VWW sample mosaic
                    (one with a person, one without)
  samples_imagenet  two 160x160x3 images of the BrainChip "imagenet_like"
                    sample pack, preprocessed exactly like the Dev Hub
                    (shorter side to 183 px, centre crop 160 x 160)
  samples_ecg       beats of the MIT-BIH test records (DS2), built by the
                    Dev Hub arrhythmia pipeline, 10 per class (N, S, V)

Every sample is classified with the akida Python package (software
simulation of the same model) and the expected class is stored with it, so
that the board result can be compared with the PC result.
"""
import argparse
import os
import sys
import types
import zipfile

import akida
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from export_model import byte_literal, c_string  # noqa: E402


def write_samples(out_dir, name, arrays, labels, expected, comment):
    """Writes the header-only sample source <out_dir>/<name>.h.

    Every sample is one string literal (fast to compile); the rows are one
    byte longer than the sample for the terminating zero.
    """
    shape = arrays[0].shape
    size = int(np.prod(shape))
    os.makedirs(out_dir, exist_ok=True)
    rows = ',\n'.join(byte_literal(bytes(a.reshape(-1).tolist()), indent='    ')
                      for a in arrays)
    text = f"""// Generated by tools/make_samples.py - do not edit.
// {comment}
//
// Header only: include it in exactly one .ino/.cpp file of a sketch.
#pragma once

#include <stdint.h>

namespace cbb15 {{
namespace samples {{

constexpr uint16_t {name}_count = {len(arrays)};
// One sample: [{']['.join(str(s) for s in shape)}] uint8.
constexpr uint32_t {name}_size = {size};

// {name}_data[i] points to sample i.
alignas(4) static const uint8_t {name}_data[{len(arrays)}][{size + 1}] = {{
{rows}}};

// Ground truth (dataset label) and akida Python simulation result.
static const char* const {name}_truth[{len(arrays)}] = {{
    {', '.join(c_string(l) for l in labels)}}};
static const int16_t {name}_expected[{len(arrays)}] = {{
    {', '.join(str(int(e)) for e in expected)}}};

}}  // namespace samples
}}  // namespace cbb15
"""
    with open(os.path.join(out_dir, f'{name}.h'), 'w', encoding='utf8', newline='\n') as f:
        f.write(text)
    stale = os.path.join(out_dir, f'{name}.cpp')
    if os.path.exists(stale):
        os.remove(stale)


def predict(model, x):
    out = model.predict(x) if not model.layers[-1].parameters.activation else model.forward(x)
    return np.argmax(out.reshape(len(x), -1), axis=1)


def vww(devhub, out_dir):
    zoo = os.path.join(devhub, 'akida1', 'model_zoo', 'vww')
    model = akida.Model(os.path.join(zoo, 'pretrained_models', 'akidanet_vww_qat.fbz'))
    mosaic = Image.open(os.path.join(zoo, 'docs', 'vww_sample_mosaic.png')).convert('RGB')
    w, h = mosaic.size
    tiles = [np.array(mosaic.crop((c * w // 5, r * h // 2, (c + 1) * w // 5, (r + 1) * h // 2))
                      .resize((96, 96), Image.BILINEAR)) for r in range(2) for c in range(5)]
    x = np.stack(tiles).astype(np.uint8)
    pred = predict(model, x)
    # Tile 0 shows a skateboarder, tile 5 a polar bear.
    pick = [0, 5]
    write_samples(out_dir, 'samples_vww', [x[i] for i in pick],
                  ['person', 'no person'], [pred[i] for i in pick],
                  'Tiles of the Dev Hub vww_sample_mosaic.png, resized to 96x96.')
    return {i: int(pred[i]) for i in pick}


def imagenet(devhub, sample_zip, out_dir):
    zoo = os.path.join(devhub, 'akida1', 'model_zoo', 'imagenet_akidanet')
    model = akida.Model(os.path.join(
        zoo, 'pretrained_models', 'akidanet_imagenet_160_alpha_0.25_qat.fbz'))
    z = zipfile.ZipFile(sample_zip)
    labels = {}
    for line in z.read('labels_validation.txt').decode().splitlines():
        if line.strip():
            name, idx = line.split()
            labels[name] = int(idx)
    images, truth = [], []
    for name in sorted(labels):
        img = Image.open(z.open(name)).convert('RGB')
        # Dev Hub imagenet_akidanet_preprocessing.py: shorter side to
        # round(160 * 1.143) = 183, then a central 160 x 160 crop.
        s = 183 / min(img.size)
        img = img.resize((int(img.size[0] * s), int(img.size[1] * s)), Image.BILINEAR)
        left, top = (img.size[0] - 160) // 2, (img.size[1] - 160) // 2
        images.append(np.array(img.crop((left, top, left + 160, top + 160))))
        truth.append(labels[name])
    x = np.stack(images).astype(np.uint8)
    pred = predict(model, x)
    correct = [i for i in range(len(x)) if pred[i] == truth[i]]
    pick = (correct + [i for i in range(len(x)) if i not in correct])[:2]
    write_samples(out_dir, 'samples_imagenet', [x[i] for i in pick],
                  [str(truth[i]) for i in pick], [pred[i] for i in pick],
                  'BrainChip imagenet_like sample pack, Dev Hub preprocessing (183 px, crop 160).')
    return {i: (int(truth[i]), int(pred[i])) for i in pick}


def ecg(devhub, data_dir, out_dir, per_class=10, seed=0):
    sys.modules.setdefault('tensorflow', types.ModuleType('tensorflow'))
    sys.path.insert(0, os.path.join(devhub, 'akida1', 'model_zoo', 'arrhythmia_classification'))
    import arrhythmia_data as A  # noqa: E402
    import joblib
    # The Dev Hub pipeline runs joblib worker processes. They would re-import
    # the module without the TensorFlow stub above, so threads are used.
    A.Parallel = lambda *a, **k: joblib.Parallel(*a, **dict(k, backend='threading'))
    cache = A._load_cache(data_dir)
    x, y = cache['x_test'], cache['y_test']
    model = akida.Model(os.path.join(devhub, 'akida1', 'model_zoo', 'arrhythmia_classification',
                                     'pretrained_models', 'arrhythmia_classification_qat.fbz'))
    rng = np.random.default_rng(seed)
    pick = []
    for c in range(A.NUM_CLASSES):
        idx = np.nonzero(y == c)[0]
        pick += list(rng.choice(idx, per_class, replace=False))
    xs = x[pick].astype(np.uint8)
    pred = predict(model, xs)
    write_samples(out_dir, 'samples_ecg', list(xs), [A.TARGET_NAMES[y[i]] for i in pick], pred,
                  'MIT-BIH DS2 beats via the Dev Hub arrhythmia_data.py pipeline (36x32x1).')
    return float((pred == y[pick]).mean())


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--devhub', required=True)
    p.add_argument('--imagenet-zip', required=True,
                   help='imagenet_like.zip from data.brainchip.com/dataset-mirror')
    p.add_argument('--mitdb', required=True, help='MIT-BIH folder (downloaded if missing)')
    p.add_argument('--out', default=os.path.join(here, '..', 'src', 'cbb15_models'))
    a = p.parse_args()
    print('vww', vww(a.devhub, a.out))
    print('imagenet', imagenet(a.devhub, a.imagenet_zip, a.out))
    print('ecg accuracy on the selected beats', ecg(a.devhub, a.mitdb, a.out))


if __name__ == '__main__':
    main()
