#!/usr/bin/env python
"""Export an Akida model (.fbz) as C++ sources for the BrainBoard1500 library.

The model is mapped for the AKD1500 with the akida 2.19.3 Python package
(hardware only, no software fallback), checked against the BB15 limits, and
written as one header-only file src/cbb15_models/<name>.h (byte arrays as
string literals plus the cbb15::Model descriptor accessors). Header only means
that a model is compiled only into the sketches that include it.

The serialized program is "program info" (a size-prefixed FlatBuffer, kept
on the host) followed by "program data" (written to a BB15 flash slot or
pushed over SPI). The header offers two accessors:

    cbb15::models::<name>()             info only, for flash slots 1..4
    cbb15::models::<name>WithProgram()  complete program, for slot 0 and the
                                        model flasher

so a sketch that boots its model from flash does not link the program data.

Usage as a script:
    python export_model.py model.fbz --name vww --labels "no person,person"
"""
import argparse
import os
import re
import zlib

import akida

# BB15 constraint (see src/cbb15/cbb15_config.h): program data per slot.
SLOT_MAX_DATA = 0xF0000 - 0x1000


class ExportError(RuntimeError):
    pass


def map_for_akd1500(model, mode=None):
    """Maps a model for the AKD1500 and returns the serialized program."""
    kwargs = {}
    if mode is not None:
        kwargs['mode'] = mode
    model.map(akida.AKD1500(), hw_only=True, **kwargs)
    if len(model.sequences) != 1:
        raise ExportError(f'{len(model.sequences)} sequences, expected 1')
    seq = model.sequences[0]
    program = bytes(seq.program)
    # "External memory" holds weights that an NP reads at run time (FNP2
    # layers). When the model boots from a flash slot, the engine points
    # those NPs straight at the program data in flash. When the model is
    # pushed over SPI (slot 0), the engine copies them into AKD1500 SRAM.
    return program, len(seq.passes), int(model.external_memory_size)


def split_program(program):
    """Returns the size of the program info prefix."""
    prefix = int.from_bytes(program[:4], 'little')
    info_size = prefix + 4
    if info_size > len(program):
        raise ExportError('corrupt program: info size beyond the end')
    return info_size


def c_identifier(name):
    ident = re.sub(r'[^0-9a-zA-Z_]', '_', name)
    if ident[0].isdigit():
        ident = '_' + ident
    return ident


def camel(name):
    parts = [p for p in re.split(r'[^0-9a-zA-Z]', name) if p]
    return parts[0].lower() + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def byte_literal(data, indent='    ', per_line=32):
    """Bytes as adjacent C string literals of hexadecimal escapes.

    GCC parses long string literals much faster than brace-enclosed lists,
    which keeps the compile time of the large model headers short.
    """
    lines = []
    for i in range(0, len(data), per_line):
        lines.append(indent + '"' + ''.join('\\x%02X' % b for b in data[i:i + per_line]) + '"')
    return '\n'.join(lines) if lines else indent + '""'


def write_sources(out_dir, name, program, info_size, input_shape, output_count,
                  labels, source, notes, extra=''):
    """Writes the header-only model source <out_dir>/<name>.h."""
    ident = c_identifier(name)
    fn = camel(name)
    data = program[info_size:]
    info_crc = zlib.crc32(program[:info_size]) & 0xFFFFFFFF
    data_crc = zlib.crc32(data) & 0xFFFFFFFF
    h, w, c = input_shape
    os.makedirs(out_dir, exist_ok=True)
    note_lines = ''.join(f'// {line}\n' for line in notes)
    label_list = ',\n    '.join(c_string(l) for l in labels) if labels else '""'
    # The arrays are one byte longer than the data for the terminating zero
    # of the string literal; sizes in the descriptor exclude it.
    text = f"""// Generated by tools/export_model.py - do not edit.
// Source: {source}
// Mapped for the AKD1500 with akida {akida.__version__}.
{note_lines}//
// Header only: include it in exactly one .ino/.cpp file of a sketch.
#pragma once

#include <stdint.h>

#include <cbb15/cbb15_types.h>

namespace cbb15 {{
namespace models {{
namespace {ident}_data {{

// Program info only (a copy of the first {info_size} bytes of the program).
alignas(4) static const uint8_t info[{info_size + 1}] =
{byte_literal(program[:info_size])};

// Complete serialized program: info followed by the program data.
alignas(4) static const uint8_t program[{len(program) + 1}] =
{byte_literal(program)};

static const char* const labels[{max(1, len(labels))}] = {{
    {label_list}}};

}}  // namespace {ident}_data
{extra}
// For flash slots 1..4: the program data is read from the BB15 flash, so
// the program array is not linked into the sketch.
inline Model {fn}() {{
  Model m;
  m.name = {c_string(name)};
  m.info = {ident}_data::info;
  m.infoSize = {info_size};
  m.blobSize = {len(program)};
  m.dataSize = {len(data)};
  m.dataCrc32 = 0x{data_crc:08X};
  m.infoCrc32 = 0x{info_crc:08X};
  m.inputHeight = {h};
  m.inputWidth = {w};
  m.inputChannels = {c};
  m.outputCount = {output_count};
  m.labels = {ident}_data::labels;
  m.labelCount = {len(labels)};
  return m;
}}

// Complete program: needed for slot 0 (SPI push) and by the model flasher.
inline Model {fn}WithProgram() {{
  Model m = {fn}();
  m.blob = {ident}_data::program;
  return m;
}}

}}  // namespace models
}}  // namespace cbb15
"""
    with open(os.path.join(out_dir, f'{name}.h'), 'w', encoding='utf8', newline='\n') as f:
        f.write(text)
    stale = os.path.join(out_dir, f'{name}.cpp')
    if os.path.exists(stale):
        os.remove(stale)
    return data_crc, info_crc


def export(fbz_or_model, name, out_dir, labels=(), source=None, mode=None,
           notes=(), extra=''):
    """Maps, validates and writes one model. Returns a summary dict."""
    model = akida.Model(fbz_or_model) if isinstance(fbz_or_model, str) else fbz_or_model
    input_shape = tuple(int(v) for v in model.input_shape)
    output_count = 1
    for v in model.output_shape:
        output_count *= int(v)
    program, passes, external = map_for_akd1500(model, mode)
    if passes != 1:
        raise ExportError(f'{passes} passes; BrainBoard1500 supports single-pass programs')
    info_size = split_program(program)
    data_size = len(program) - info_size
    if data_size > SLOT_MAX_DATA:
        raise ExportError(f'program data {data_size} B exceeds a 1 MiB flash slot '
                          f'({SLOT_MAX_DATA} B usable)')
    if labels and len(labels) != output_count and not model.learning:
        raise ExportError(f'{len(labels)} labels for {output_count} outputs')
    write_sources(out_dir, name, program, info_size, input_shape, output_count,
                  list(labels), source or str(fbz_or_model),
                  list(notes) + [f'Passes: {passes}, program {len(program)} B, '
                                 f'info {info_size} B, data {data_size} B, '
                                 f'external memory {external} B.'],
                  extra)
    return dict(name=name, program=len(program), info=info_size, data=data_size,
                passes=passes, external=external, input=input_shape,
                outputs=output_count)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('fbz')
    parser.add_argument('--name', required=True)
    parser.add_argument('--labels', default='', help='comma separated class names')
    parser.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..',
                                                      'src', 'cbb15_models'))
    parser.add_argument('--minimal', action='store_true',
                        help='use MapMode.Minimal (fewest NPs)')
    args = parser.parse_args()
    labels = [l.strip() for l in args.labels.split(',')] if args.labels else []
    mode = akida.MapMode.Minimal if args.minimal else None
    print(export(args.fbz, args.name, args.out, labels, mode=mode))


if __name__ == '__main__':
    main()
